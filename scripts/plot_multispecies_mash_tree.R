#!/usr/bin/env Rscript
# Validate the complete Mash distance matrix, infer neighbor-joining, plot unrooted.
args <- commandArgs(trailingOnly = TRUE)
if (length(args) != 3L) stop('Usage: Rscript plot_multispecies_mash_tree.R MANIFEST DISTANCES STAGE')
if (!requireNamespace('ape', quietly = TRUE)) stop('R package ape is required')
manifest <- read.delim(args[1], sep='\t', check.names=FALSE, stringsAsFactors=FALSE)
required <- c('genome_id','genome_fasta','source_group','display_label')
if (!all(required %in% names(manifest))) stop('Manifest missing required columns')
if (nrow(manifest) != 87L || anyDuplicated(manifest$genome_id) || anyDuplicated(manifest$genome_fasta)) stop('Panel must contain 87 unique IDs and FASTA paths')
expected <- c('NCBI reference'=34L, 'Mullis reference'=42L, 'Buck isolate'=5L, 'SRR isolate'=6L)
counts <- table(factor(manifest$source_group, levels=names(expected)))
if (any(counts != expected) || anyNA(manifest$source_group)) stop('Unexpected source-group counts')
raw <- read.delim(args[2], sep='\t', header=FALSE, stringsAsFactors=FALSE)
if (ncol(raw) != 5L || nrow(raw) != nrow(manifest)^2) stop('Mash distance output is incomplete or malformed')
root <- normalizePath('.', mustWork=TRUE)
resolve <- function(path) normalizePath(ifelse(startsWith(path, '/'), path, file.path(root,path)), mustWork=TRUE)
keys <- vapply(manifest$genome_fasta, resolve, character(1))
if (anyDuplicated(keys)) stop('Resolved FASTA paths are not unique')
i <- match(vapply(raw[[1]], resolve, character(1)), keys)
j <- match(vapply(raw[[2]], resolve, character(1)), keys)
if (anyNA(i) || anyNA(j) || anyDuplicated(paste(i,j,sep=':'))) stop('Unknown or repeated Mash pair')
d <- suppressWarnings(as.numeric(raw[[3]]))
if (anyNA(d) || any(!is.finite(d)) || any(d < 0) || any(d > 1)) stop('Invalid Mash distances')
mat <- matrix(NA_real_, nrow(manifest), nrow(manifest), dimnames=list(manifest$genome_id,manifest$genome_id))
mat[cbind(i,j)] <- d
if (anyNA(mat) || max(abs(mat-t(mat))) > 1e-8 || any(diag(mat) > 1e-8)) stop('Distance matrix is incomplete, asymmetric, or nonzero on diagonal')
if (any(mat[upper.tri(mat)] == 1)) stop('At least one pair has no shared hashes; NJ placement is unreliable')
mat <- (mat+t(mat))/2
tree <- ape::nj(as.dist(mat))
if (!setequal(tree$tip.label, manifest$genome_id) || ape::is.rooted(tree)) stop('Unexpected tree tips or rooted tree')
negative <- sum(tree$edge.length < -1e-8)
if (negative > 0) warning(negative, ' negative NJ branch lengths; inspect before interpretation')
stage <- args[3]
write.table(cbind(genome_id=rownames(mat),as.data.frame(mat,check.names=FALSE)), file=file.path(stage,'metadata','mash_distance_matrix.tsv'), sep='\t', quote=FALSE, row.names=FALSE)
ape::write.tree(tree, file=file.path(stage,'tree','unrooted_mash_nj.nwk'))
styles <- data.frame(source_group=names(expected), color=c('#6B7280','#249760','#D43F3A','#2670C4'), pch=c(22,23,21,24), stringsAsFactors=FALSE)
idx <- match(tree$tip.label, manifest$genome_id)
style_idx <- match(manifest$source_group[idx], styles$source_group)
labels <- manifest$display_label[idx]
plot_tree <- function() {
  par(mar=c(1,1,4,1))
  ape::plot.phylo(tree, type='unrooted', show.tip.label=TRUE, tip.color=styles$color[style_idx], cex=0.48, font=1, no.margin=FALSE)
  ape::tiplabels(pch=styles$pch[style_idx], bg=styles$color[style_idx], col=styles$color[style_idx], cex=0.7)
  title('Vibrio reference and isolate genome distances: Mash / neighbor joining', cex.main=1.1)
  legend('topleft', legend=styles$source_group, pch=styles$pch, pt.bg=styles$color, col=styles$color, bty='n', cex=0.85)
  mtext('Unrooted exploratory distance tree; branch lengths in Mash distance units', side=1, line=-1, cex=0.8)
}
pdf(file.path(stage,'figures','unrooted_mash_nj.pdf'), width=24, height=20, onefile=FALSE)
plot_tree()
dev.off()
png(file.path(stage,'figures','unrooted_mash_nj.png'), width=3600, height=3000, res=150)
plot_tree()
dev.off()
writeLines(c(paste0('genomes\t',nrow(manifest)),paste0('pairwise_distances\t',nrow(raw)),paste0('negative_nj_branches\t',negative),'rooting\tunrooted','method\tMash k=21 s=10000; neighbor joining'),file.path(stage,'metadata','tree_qc.tsv'))
